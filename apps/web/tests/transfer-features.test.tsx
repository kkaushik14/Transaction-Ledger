/** Transfer components and intent safety are verified independently before workspace integration. */
import { act, fireEvent, render, screen } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { MemoryRouter } from 'react-router-dom';
import { describe, expect, it, vi } from 'vitest';
import {
  createTransferRequestSchema,
  type CreateTransferRequest,
  type CreateTransferResponse,
} from '@ledger/contracts';
import { TransferForm, TransferReview, TransferReceipt } from '../src/features/transfers/index.js';
import { readTransferIntent, saveTransferIntent } from '../src/features/transfers/hooks/index.js';
import { createTransfer } from '../src/api/index.js';
import { accountId, jsonResponse } from './fixtures';

const destination = 'bbbbbbbb-0000-4000-8000-000000000002';
const transferId = 'cccccccc-0000-4000-8000-000000000003';
const command = createTransferRequestSchema.parse({
  source_account_id: accountId,
  destination_account_id: destination,
  amount: '1.5',
  reference_id: 'transfer-ref',
  description: 'Shared expense',
});
/** Builds a contract-valid response from the actual command, including dynamic generated references. */
function receipt(input: CreateTransferRequest = command): CreateTransferResponse {
  const leg = {
    amount: input.amount,
    reference_id: input.reference_id,
    description: input.description,
    transfer_id: transferId,
    created_at: '2026-10-28T00:00:00.000Z',
  };
  return {
    data: {
      transfer: { ...input, id: transferId, created_at: leg.created_at },
      debit: {
        ...leg,
        id: 'dddddddd-0000-4000-8000-000000000004',
        account_id: input.source_account_id,
        type: 'debit',
      },
      credit: {
        ...leg,
        id: 'eeeeeeee-0000-4000-8000-000000000005',
        account_id: input.destination_account_id,
        type: 'credit',
      },
      source_account_balance: '8.50',
      destination_account_balance: '1.50',
    },
  };
}
/** Isolated feature fixture uses routing only for receipt navigation links. */
function form(onChanged = vi.fn(), source = accountId) {
  return render(
    <MemoryRouter>
      <TransferForm key={source} sourceAccountId={source} onChanged={onChanged} />
    </MemoryRouter>,
  );
}
/** Reviews a valid transfer; this must not send a POST. */
async function review(amount = '1.5') {
  await userEvent.type(screen.getByLabelText('Destination account ID'), destination.toUpperCase());
  await userEvent.type(screen.getByLabelText('Transfer amount'), amount);
  await userEvent.type(screen.getByLabelText('Transfer description (optional)'), 'Shared expense');
  await userEvent.click(screen.getByRole('button', { name: 'Review transfer' }));
}
/** Real HTTP envelope, while the command reference remains generated by the feature. */
function successfulFetch() {
  return vi.fn<typeof fetch>(async (_url, init) =>
    jsonResponse(receipt(JSON.parse(String(init?.body))), 201),
  );
}

describe('transfer review and receipt', () => {
  it('reviews the complete immutable command and requires explicit confirm/edit actions', async () => {
    const confirm = vi.fn(),
      edit = vi.fn();
    render(<TransferReview payload={command} onConfirm={confirm} onEdit={edit} focusOnMount />);
    expect(screen.getByRole('heading', { name: 'Review transfer' })).toHaveFocus();
    for (const value of [
      accountId,
      destination,
      command.amount,
      command.description,
      command.reference_id,
    ])
      expect(screen.getByText(value)).toBeInTheDocument();
    await userEvent.click(screen.getByRole('button', { name: 'Confirm transfer' }));
    await userEvent.click(screen.getByRole('button', { name: 'Edit transfer' }));
    expect(confirm).toHaveBeenCalledTimes(1);
    expect(edit).toHaveBeenCalledTimes(1);
  });
  it('blocks pending confirmation and presents only committed server data with recipient navigation', () => {
    const view = render(<TransferReview payload={command} onConfirm={() => {}} pending />);
    expect(screen.getByRole('button', { name: 'Transferring…' })).toBeDisabled();
    view.unmount();
    render(
      <MemoryRouter>
        <TransferReceipt result={receipt().data} />
      </MemoryRouter>,
    );
    expect(screen.getByRole('status')).toHaveTextContent('Transfer complete');
    expect(screen.getByRole('heading', { name: 'Transfer receipt' })).toHaveFocus();
    expect(screen.getByText(transferId)).toBeInTheDocument();
    expect(screen.getByRole('link', { name: 'Open destination account' })).toHaveAttribute(
      'href',
      `/accounts/${destination}`,
    );
    expect(screen.getByText('Source balance after transfer')).toBeInTheDocument();
  });
});

describe('transfer command workflow', () => {
  it('treats an actual HTTP timeout as uncertain rather than claiming a rollback', async () => {
    vi.useFakeTimers();
    vi.stubGlobal(
      'fetch',
      (_url: RequestInfo | URL, options?: RequestInit) =>
        new Promise<Response>((_resolve, reject) => {
          options?.signal?.addEventListener('abort', () =>
            reject(new DOMException('Timed out', 'AbortError')),
          );
        }),
    );
    try {
      const pending = expect(createTransfer(command)).rejects.toMatchObject({
        code: 'NETWORK_ERROR',
        uncertain: true,
      });
      await vi.advanceTimersByTimeAsync(20001);
      await pending;
    } finally {
      vi.useRealTimers();
    }
  });
  it.each([
    ['destination', 'not-a-uuid', 'Destination account ID'],
    ['destination', accountId.toUpperCase(), 'Destination account ID'],
    ['amount', '0', 'Transfer amount'],
    ['amount', '1.001', 'Transfer amount'],
    ['amount', '1e2', 'Transfer amount'],
    ['amount', '1000000000000000000', 'Transfer amount'],
    ['description', 'x'.repeat(501), 'Transfer description (optional)'],
  ])('rejects invalid %s before HTTP and focuses the field', async (field, value, label) => {
    const fetcher = successfulFetch();
    vi.stubGlobal('fetch', fetcher);
    form();
    await userEvent.type(
      screen.getByLabelText('Destination account ID'),
      field === 'destination' ? value : destination,
    );
    await userEvent.type(
      screen.getByLabelText('Transfer amount'),
      field === 'amount' ? value : '1',
    );
    if (field === 'description')
      fireEvent.change(screen.getByLabelText(label), { target: { value } });
    await userEvent.click(screen.getByRole('button', { name: 'Review transfer' }));
    expect(screen.getByLabelText(label)).toHaveAttribute('aria-invalid', 'true');
    expect(screen.getByLabelText(label)).toHaveFocus();
    if (value === 'not-a-uuid')
      expect(screen.getByText(/Enter a valid Account ID/)).toBeInTheDocument();
    expect(fetcher).not.toHaveBeenCalled();
  });
  it('normalizes the reviewed payload, allows edits before sending, and refreshes after one confirmed POST', async () => {
    const fetcher = successfulFetch(),
      changed = vi.fn();
    vi.stubGlobal('fetch', fetcher);
    form(changed);
    await review();
    expect(fetcher).not.toHaveBeenCalled();
    await userEvent.click(screen.getByRole('button', { name: 'Edit transfer' }));
    expect(screen.getByLabelText('Transfer amount')).toHaveValue('1.5');
    await userEvent.click(screen.getByRole('button', { name: 'Review transfer' }));
    await userEvent.click(screen.getByRole('button', { name: 'Confirm transfer' }));
    expect(await screen.findByText('Transfer complete')).toBeInTheDocument();
    const payload = JSON.parse(String(fetcher.mock.calls[0]?.[1]?.body));
    expect(payload).toMatchObject({
      source_account_id: accountId,
      destination_account_id: destination,
      amount: '1.50',
      description: 'Shared expense',
    });
    expect(payload.reference_id).toMatch(/^[0-9a-f-]{36}$/);
    expect(fetcher.mock.calls[0]?.[0]).toBe('http://localhost:3000/api/v1/transfers');
    expect(changed).toHaveBeenCalledTimes(1);
    expect(readTransferIntent(accountId)).toBeUndefined();
  });
  it('blocks double confirmation and Enter submission while the write is pending', async () => {
    let finish: ((value: Response) => void) | undefined;
    const fetcher = vi.fn<typeof fetch>(
      () =>
        new Promise((resolve) => {
          finish = resolve;
        }),
    );
    vi.stubGlobal('fetch', fetcher);
    form();
    await review();
    const confirm = screen.getByRole('button', { name: 'Confirm transfer' });
    fireEvent.click(confirm);
    fireEvent.click(confirm);
    fireEvent.submit(screen.getByRole('form', { name: 'Transfer between accounts' }));
    expect(fetcher).toHaveBeenCalledTimes(1);
    expect(screen.getByRole('button', { name: 'Transferring…' })).toBeDisabled();
    await act(async () => {
      finish?.(jsonResponse(receipt(JSON.parse(String(fetcher.mock.calls[0]?.[1]?.body))), 201));
    });
  });
  it.each([
    [400, 'VALIDATION_ERROR'],
    [404, 'ACCOUNT_NOT_FOUND'],
    [422, 'INSUFFICIENT_BALANCE'],
    [422, 'BALANCE_LIMIT_EXCEEDED'],
  ])('preserves editable fields after known rejection %s/%s', async (status, code) => {
    vi.stubGlobal(
      'fetch',
      vi.fn<typeof fetch>(async () =>
        jsonResponse(
          {
            error: {
              code,
              message: 'Transfer rejected',
              support_ticket_id: '11111111-1111-4111-8111-111111111111',
              action: 'fix_input',
            },
          },
          status,
        ),
      ),
    );
    const changed = vi.fn();
    form(changed);
    await review();
    await userEvent.click(screen.getByRole('button', { name: 'Confirm transfer' }));
    expect(await screen.findByRole('alert')).toHaveTextContent(
      code === 'VALIDATION_ERROR'
        ? 'Check the entered details'
        : code === 'ACCOUNT_NOT_FOUND'
          ? 'not found'
          : code === 'INSUFFICIENT_BALANCE'
            ? 'insufficient balance'
            : 'balance limit',
    );
    expect(screen.getByLabelText('Transfer amount')).toHaveValue('1.5');
    expect(screen.getByLabelText('Destination account ID')).toHaveValue(destination.toUpperCase());
    expect(readTransferIntent(accountId)).toBeUndefined();
    expect(changed).toHaveBeenCalledTimes(status === 422 ? 1 : 0);
  });
  it.each(['DUPLICATE_TRANSFER', 'DUPLICATE_TRANSACTION'])(
    'treats %s as a conflict, preserves its intent, and requires review before a new reference',
    async (code) => {
      const fetcher = vi.fn<typeof fetch>(async () =>
        jsonResponse(
          {
            error: {
              code,
              message: 'Already used',
              support_ticket_id: '11111111-1111-4111-8111-111111111111',
              action: 'fix_input',
            },
          },
          409,
        ),
      );
      const changed = vi.fn();
      vi.stubGlobal('fetch', fetcher);
      form(changed);
      await review();
      await userEvent.click(screen.getByRole('button', { name: 'Confirm transfer' }));
      expect(await screen.findByRole('alert')).toHaveTextContent(
        'earlier result has not been confirmed',
      );
      expect(screen.queryByText('Transfer complete')).not.toBeInTheDocument();
      expect(readTransferIntent(accountId)).toBeDefined();
      expect(changed).toHaveBeenCalledTimes(1);
      expect(screen.getByRole('button', { name: 'New transfer' })).toBeDisabled();
      await userEvent.click(screen.getByRole('checkbox'));
      await userEvent.click(screen.getByRole('button', { name: 'New transfer' }));
      expect(screen.getByLabelText('Transfer amount')).toHaveValue('');
      expect(fetcher).toHaveBeenCalledTimes(1);
      expect(readTransferIntent(accountId)).toBeUndefined();
    },
  );
  it('restores an uncertain command on reload without auto-sending and retries it identically', async () => {
    const fetcher = vi.fn<typeof fetch>(async () => {
      throw new TypeError('offline');
    });
    vi.stubGlobal('fetch', fetcher);
    const first = form();
    await review();
    await userEvent.click(screen.getByRole('button', { name: 'Confirm transfer' }));
    expect(await screen.findByText(/Transfer result unconfirmed/)).toBeInTheDocument();
    const original = String(fetcher.mock.calls[0]?.[1]?.body);
    first.unmount();
    const changed = vi.fn();
    form(changed);
    expect(fetcher).toHaveBeenCalledTimes(1);
    expect(screen.queryByLabelText('Transfer amount')).not.toBeInTheDocument();
    fetcher.mockImplementation(successfulFetch());
    await userEvent.click(screen.getByRole('button', { name: 'Retry same transfer' }));
    expect(await screen.findByText('Transfer complete')).toBeInTheDocument();
    expect(String(fetcher.mock.calls[1]?.[1]?.body)).toBe(original);
    expect(changed).toHaveBeenCalledTimes(1);
  });
  it.each(['server', 'invalid', 'mismatched'])(
    'keeps %s responses uncertain without fabricating rollback or success',
    async (kind) => {
      vi.stubGlobal(
        'fetch',
        vi.fn<typeof fetch>(async (_url, init) => {
          if (kind === 'server')
            return jsonResponse(
              {
                error: {
                  code: 'INTERNAL_ERROR',
                  message: 'Unconfirmed',
                  support_ticket_id: '11111111-1111-4111-8111-111111111111',
                  action: 'fix_input',
                },
              },
              500,
            );
          if (kind === 'invalid') return new Response('not json', { status: 201 });
          return jsonResponse(receipt({ ...JSON.parse(String(init?.body)), amount: '2.00' }), 201);
        }),
      );
      form();
      await review();
      await userEvent.click(screen.getByRole('button', { name: 'Confirm transfer' }));
      expect(await screen.findByText(/Transfer result unconfirmed/)).toBeInTheDocument();
      expect(screen.getByRole('button', { name: 'Retry same transfer' })).toBeEnabled();
      expect(readTransferIntent(accountId)?.amount).toBe('1.50');
      expect(screen.queryByText('Transfer complete')).not.toBeInTheDocument();
    },
  );
  it('fails before sending if the command cannot be persisted', async () => {
    const set = vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => {
      throw new Error('Storage blocked');
    });
    const fetcher = successfulFetch();
    vi.stubGlobal('fetch', fetcher);
    try {
      form();
      await review();
      await userEvent.click(screen.getByRole('button', { name: 'Confirm transfer' }));
      expect(await screen.findByRole('alert')).toHaveTextContent(
        'Retry details could not be saved',
      );
      expect(fetcher).not.toHaveBeenCalled();
      expect(screen.queryByRole('button', { name: 'Confirm transfer' })).not.toBeInTheDocument();
      set.mockRestore();
      await userEvent.click(screen.getByRole('button', { name: 'Retry' }));
      expect(await screen.findByText('Transfer complete')).toBeInTheDocument();
      expect(fetcher).toHaveBeenCalledTimes(1);
    } finally {
      set.mockRestore();
    }
  });
  it('ignores corrupt/cross-account session data and never moves an unresolved intent to another account', () => {
    sessionStorage.setItem(`transaction-ledger:transfer-intent:${accountId}`, '{bad');
    expect(readTransferIntent(accountId)).toBeUndefined();
    saveTransferIntent(accountId, command);
    const view = form(vi.fn(), destination);
    expect(screen.getByLabelText('Destination account ID')).toHaveValue('');
    view.unmount();
    sessionStorage.setItem(
      `transaction-ledger:transfer-intent:${destination}`,
      JSON.stringify(command),
    );
    expect(readTransferIntent(destination)).toBeUndefined();
    expect(readTransferIntent(accountId)).toEqual(command);
  });
  it('a delayed response from an old form cannot erase a newer unresolved command', async () => {
    let finish: ((value: Response) => void) | undefined;
    const fetcher = vi.fn<typeof fetch>(
      () =>
        new Promise((resolve) => {
          finish = resolve;
        }),
    );
    vi.stubGlobal('fetch', fetcher);
    const view = form();
    await review();
    await userEvent.click(screen.getByRole('button', { name: 'Confirm transfer' }));
    const original = readTransferIntent(accountId)!;
    view.unmount();
    const next = { ...original, reference_id: 'newer-reference', amount: '2.00' };
    saveTransferIntent(accountId, next);
    await act(async () => {
      finish?.(jsonResponse(receipt(original), 201));
    });
    expect(readTransferIntent(accountId)).toEqual(next);
  });
});
